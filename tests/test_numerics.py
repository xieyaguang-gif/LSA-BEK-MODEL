from pathlib import Path

import numpy as np
import pytest

from llsa import LocalProblem, Parameters, derivatives, load_baseflow, saddle, solve_bek, spatial, temporal, temporal_near
from llsa.spectral import chebyshev

DATA = Path(__file__).resolve().parents[1]/"data"


@pytest.fixture(scope="module")
def bek():
    return solve_bek(-0.751)


def test_ekman_analytic():
    f = solve_bek(0, zmax=24, tol=1e-9, samples=8001)
    z = np.linspace(0, 20, 101)
    q = f.sample(z)
    np.testing.assert_allclose(q.U, -np.exp(-z)*np.sin(z), atol=2e-7)
    np.testing.assert_allclose(q.V, 1-np.exp(-z)*np.cos(z), atol=2e-7)
    np.testing.assert_allclose(q.W, 1-np.exp(-z)*(np.sin(z)+np.cos(z)), atol=2e-7)


@pytest.mark.parametrize("stretch", [0, 0.25])
def test_mapping_derivatives(stretch):
    g = chebyshev(64, 20, stretch)
    assert g.z[0] == 20 and g.z[-1] == 0
    assert np.all(np.diff(g.z) < 0)
    # Exponentials resolve well on both grids; test derivatives in physical z.
    c = np.linalg.solve(g.S, np.exp(-g.z/4))
    np.testing.assert_allclose(g.D@c, -np.exp(-g.z/4)/4, atol=2e-11)
    np.testing.assert_allclose(g.D2@c, np.exp(-g.z/4)/16, atol=2e-8)


def test_legacy_table_layouts_and_domain():
    a = load_baseflow(DATA/"temporal_irsm_flow.txt")
    b = load_baseflow(DATA/"spatial_irsm_flow.txt", layout="spatial")
    np.testing.assert_allclose(a.state, b.state)
    with pytest.raises(ValueError, match="exceeds"):
        LocalProblem(a, Parameters(zmax=20))
    LocalProblem(a, Parameters(n=16, zmax=19.8))


@pytest.mark.parametrize("boundary", ["matlab", "paper"])
def test_eigenpairs_boundaries_and_spatial_roundtrip(bek, boundary):
    p = LocalProblem(bek, Parameters(n=24, boundary=boundary))
    alpha = .26+.1j
    s = temporal(p, alpha)
    k = s.select()
    w, q = s.values[k], s.vectors[:, k]
    assert s.residuals[k] < 1e-12
    uvwp = p.fields(q)
    np.testing.assert_allclose(uvwp[[0, -1], :3], 0, atol=1e-9)
    pressure_end = 0 if boundary == "matlab" else -1
    derivative_end = -1 if boundary == "matlab" else 0
    assert abs(uvwp[pressure_end, 3]) < 1e-9
    assert abs(p.grid.D[derivative_end]@q.reshape(-1, 4)[:, 2]) < 1e-9
    ss = spatial(p, w)
    j = ss.select(alpha)
    assert abs(ss.values[j]-alpha) < 1e-8


def test_adjoint_derivatives(bek):
    p = LocalProblem(bek, Parameters(n=32))
    a, h = .26+.1j, 1e-4
    s = temporal(p, a, left=True)
    k = s.select()
    w = s.values[k]
    d1, d2 = derivatives(p, a, s, k)
    vals = []
    for aa in [a-h, a+h]:
        ss = temporal(p, aa)
        vals.append(ss.values[ss.select(w)])
    assert abs(d1-(vals[1]-vals[0])/(2*h)) < 1e-7
    assert abs(d2-(vals[1]+vals[0]-2*w)/h**2) < 1e-5


def test_targeted_solver(bek):
    p = LocalProblem(bek, Parameters(n=32))
    full = temporal(p, .26)
    partial = temporal_near(p, .26, .028+.008j, count=4)
    assert len(partial.values) == 4
    for w in partial.values:
        assert min(abs(full.values-w)) < 1e-8


def test_archived_matlab_values():
    # Independent six-decimal outputs, not values generated by this implementation.
    p = LocalProblem(solve_bek(-1), Parameters(re=530, ro=-1, beta=67, n=32))
    for re, ar, minus_ai, beta, wi, minus_wr in np.loadtxt(DATA/"matlab_map_reference.csv", delimiter=","):
        s = temporal(p, ar-1j*minus_ai)
        w = s.values[s.select()]
        assert abs(w-complex(-minus_wr, wi)) < 8e-7


def test_saddle_and_resolution():
    f = solve_bek(-1)
    results = []
    for n in [48, 64]:
        p = LocalProblem(f, Parameters(re=530, ro=-1, beta=67, n=n))
        r = saddle(p, .213+.123j, .0311+.00035j)
        assert r.converged and abs(r.group_velocity) < 1e-10
        results.append(r)
    assert abs(results[0].omega-results[1].omega) < 2e-6
    assert abs(results[0].alpha-results[1].alpha) < 1e-4
    r = saddle(p, .26+.1j, .03+.001j, max_iter=1)
    assert not r.converged
    assert r.alpha == r.history[-1]["alpha"]
    assert r.omega == r.history[-1]["omega"]


