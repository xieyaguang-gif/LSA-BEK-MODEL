"""Collect saved evidence and generate LaTeX tables; no stability solve is run."""
from pathlib import Path
import hashlib
import json

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT/'docs/tables'


def read(name):
    return json.loads((ROOT/name).read_text())


def c(value, digits=6):
    real, imag = value
    sign = '+' if imag >= 0 else '-'
    return '$'+f'{real:.{digits}f}{sign}{abs(imag):.{digits}f}\\ii$'


def table(name, headers, rows, caption, align=None, flexible=False):
    align = align or 'l'+'r'*(len(headers)-1)
    opening = (r'\begin{tabularx}{\linewidth}{'+align+'}' if flexible else
               r'\begin{tabular}{'+align+'}')
    ending = r'\end{tabularx}' if flexible else r'\end{tabular}'
    body = ['% Generated by examples/prepare_pier_report.py', r'\begin{table}[htbp]',
            r'\centering\small', opening, r'\toprule', ' & '.join(headers)+r'\\', r'\midrule']
    body += [' & '.join(map(str, row))+r'\\' for row in rows]
    body += [r'\bottomrule', ending, r'\caption{'+caption+'}', r'\label{tab:'+name+'}',
             r'\end{table}', '']
    (OUT/(name+'.tex')).write_text('\n'.join(body))


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    refs = read('src/llsa/secondary/references.json')
    times = read('docs/pier_time_validation.json')
    audit = read('docs/pier_equation_audit.json')
    old = read('docs/pier2007_audit.json')
    primary = {}
    for n in (40, 60):
        file = ROOT/f'results/pier2003/wave_n{n}_h5.npz'
        with np.load(file, allow_pickle=False) as d:
            primary[n] = {k: d[k].tolist() for k in ['alpha', 'omega', 'energies', 'radius', 'beta', 'n']}
        primary[n]['sha256'] = hashlib.sha256(file.read_bytes()).hexdigest()
    data = dict(date='2026-09-15', primary=primary, paper=refs,
                time_cases={k:times['cases'][k] for k in ['temporal_converged','weighted_converged',
                    'weighted_n80_z320','weighted_n96_z640','weighted_n96_z1280','published_alpha','temporal_seed19']},
                wall_comparisons=old['wall_comparisons'], equation_audit=audit,
                pressure_elimination=times['corrected_pressure_elimination'])
    (ROOT/'docs/pier_report_data.json').write_text(json.dumps(data, indent=2)+'\n')
    paper = {n:next(r for r in refs['table2'] if r['n']==n and r['H']==5) for n in (40,60)}
    rows = [[r'$\alpha$', f"{paper[40]['alpha']:.5f}", f"{primary[40]['alpha']:.8f}",
             f"{paper[60]['alpha']:.5f}", f"{primary[60]['alpha']:.8f}"]]
    rows += [[f'$E_{i+1}$', f"{paper[40]['energies'][i]:.2f}", f"{primary[40]['energies'][i]:.6f}",
              f"{paper[60]['energies'][i]:.2f}", f"{primary[60]['energies'][i]:.6f}"] for i in range(5)]
    table('primary', ['量','论文 $N=40$','本项目 $N=40$','论文 $N=60$','本项目 $N=60$'], rows,
          r'主波对照，$H=5$、parallel 均值。当前时间推进和 Floquet 比较共享最后一列主波。')
    case = data['time_cases']['weighted_n96_z1280']
    eig = case['spectral_comparison']['omega_hat']
    fit = case['runs'][-1]['fits'][-1]
    ah = times['candidate_alpha_hat']
    table('secondary', ['量','论文','当前 Floquet','时间推进'],
          [[r'$\operatorname{Re}\hat\alpha$', r'约 $-0.0012$', '$'+f'{ah[0]:.8f}'+'$','输入同左'],
           [r'$\operatorname{Im}\hat\alpha$', r'约 $-0.0369$', '$'+f'{ah[1]:.8f}'+'$','输入同左'],
           [r'$\operatorname{Re}\hat\omega$', '8.5207',f'{eig[0]:.6f}', f"{fit['omega_real']:.6f}"],
           [r'$\operatorname{Im}\hat\omega$', '1.1597',f'{eig[1]:.6f}', f"{fit['growth']:.6f}"]],
          r'二次基准对照。论文频率来自表3，舍入波数来自式(7.8)。时间推进不独立搜索鞍点。')
    rows = []
    for n in (30,40,60):
        pair = {r['secondary_wall_condition']:r for r in old['wall_comparisons'] if r['n']==n}
        rows.append([n,c(pair['pressure']['secondary']['omega_hat']),c(pair['continuity']['secondary']['omega_hat'])])
    table('wall_history',['$N$','旧 pressure 壁面','continuity 壁面'],rows,
          'parallel 主波下二次壁面离散的历史比较；主波在各自网格计算。')
    tr = data['time_cases']['temporal_converged']; wr = data['time_cases']['weighted_converged']
    rows = [[f"{a['dt']:.5f}",f"{a['fits'][-1]['growth']:.9f}",f"{b['fits'][-1]['growth']:.9f}"]
            for a,b in zip(tr['runs'],wr['runs'])]
    rows += [['二阶外推',f"{tr['time_convergence']['growth']['extrapolated']:.9f}",
             f"{wr['time_convergence']['growth']['extrapolated']:.9f}"],
             ['实测阶数',f"{tr['time_convergence']['growth']['observed_order']:.5f}",
              f"{wr['time_convergence']['growth']['observed_order']:.5f}"]]
    table('time_steps',[r'$\Delta t$',r'实 $\hat\alpha=0$ 的 $\sigma$',r'候选复 $\hat\alpha$ 的 $\sigma$'],rows,
          r'时间步检查。实波数固定 $N=64,Z=320$；复波数固定 $N=80,Z=640$。外推不消除空间误差。')
    rows=[]
    for key in ['weighted_n80_z320','weighted_converged','weighted_n96_z640','weighted_n96_z1280']:
        d=data['time_cases'][key]; r=min(d['runs'], key=lambda r:abs(r['dt']-.0005)); f=r['fits'][-1]
        rows.append([d['parameters']['n'],f"{d['parameters']['zmax']:.0f}",f"{f['omega_real']:.8f}",f"{f['growth']:.8f}"])
    table('far_field',['$N$','$Z$',r'$\operatorname{Re}\hat\omega$',r'$\sigma$'],rows,
          r'固定主波及候选复波数的空间检查，均取 $\Delta t=0.0005$。')
    rows=[]
    for title,key in [('实波数零点','temporal_converged'),('论文舍入波数','published_alpha')]:
        d=data['time_cases'][key]; f=d['runs'][-1]['fits'][-1]
        rows.append([title,c(d['spectral_comparison']['omega_hat']),c([f['omega_real'],f['growth']])])
    table('other_points',['指定波数检查','Floquet','时间推进'],rows,
          r'实波数零点为 $\hat\alpha=0$；论文舍入波数为 $-0.0012-0.0369\ii$。两行均为给定波数计算。')
    rows=[]
    for record in data['pressure_elimination']['runs']:
        for r in record['records']:
            rows.append([r['n'],f"{r['zmax']:.0f}",c(r['omega_hat'])])
    table('pressure_elimination',['$N$','$Z$',r'修正高阶导数后的 $\hat\omega$'],rows,
          r'独立消元谱在当前候选复波数处的核对；脚本在目标网格重求主波。')
    variants=audit['primary_variants']
    rows=[]
    for n in (40,60):
        r=next(v for v in variants if v['n']==n and v['name']=='literal_paper_mean_boundaries')
        d=r['physical_defects']
        rows.append([n,f"{r['newton_residual']:.2e}",f"{d['mean_continuity']:.2e}",
                     f"{d['mean_off_node_continuity']:.5f}",f"{d['mean_wall_continuity']:.5f}"])
    table('literal_mean',['$N$','Newton 残差','均值节点残差','均值节点间残差','均值壁面残差'],rows,
          '现有配点离散恢复论文全部均值边界后的诊断。小代数残差伴随严重物理约束缺陷，未采用这组解。')
    rows=[['当前 parallel',f"{primary[60]['alpha']:.8f}",f"{primary[60]['energies'][0]:.5f}",
           f'{eig[1]:.8f}',r'$Dw_0+u_0/R$ 不为零']]
    for key,title,note in [('cylindrical_free_mean_far_boundary','cylindrical',
                           r'$w_0(\infty)\ne0$'),
                          ('literal_paper_mean_boundaries','恢复文字边界','节点间与壁面连续性失败')]:
        r=next(v for v in variants if v['n']==60 and v['name']==key)
        sigma=f"{r['secondary']['omega_hat'][1]:.8f}" if r['secondary'] else '不采用'
        rows.append([title,f"{r['alpha']:.8f}",f"{r['energies'][0]:.5f}",sigma,note])
    rows.append(['论文 $N=40$','0.34616','621.03','1.1597','实际均值实现尚未获得'])
    table('mean_models',['主波处理',r'$\alpha$','$E_1$',r'$\sigma$','限制'],rows,
          '均值处理的影响。本项目三行均为 $N=60$；已计算的二次谱采用 continuity 壁面。',
          align='p{2.4cm}rrrY',flexible=True)
    print('Saved docs/pier_report_data.json and',len(list(OUT.glob('*.tex'))),'LaTeX tables')


if __name__ == '__main__':
    main()
